import sys
import os

sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), '../model/ejs_temp_ann')))
sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), '../preprocessing')))

from S99_build_model import build_ejs_temp_ann
from nio_adapter import format_inputs_for_ejs_ann, interpolate_13_to_15_depths

def run_zeroshot_experiment():
    print("--- Experiment A: Zero-Shot North Indian Ocean Transfer ---")
    
    # 1. Initialize Model
    model = build_ejs_temp_ann()
    print("Model initialized.")

    # 2. Emulate getting data from CMEMS
    print("Fetching Bay of Bengal surface patches...")
    # (In a real run, we load the NetCDF files generated by data_ingestion.py here)
    
    # 3. Regrid and adapt to model's exact tensor expectations
    spatial_tensor, aux_tensor = format_inputs_for_ejs_ann(None, None, None)
    print("Data regridded to 1/12 degree (25x25) spatial patches.")
    
    # 4. Inference
    predictions_13 = model.predict([spatial_tensor, aux_tensor])
    
    # 5. Output Mapping (13 depths -> 15 standard depths)
    final_15_depths = interpolate_13_to_15_depths(predictions_13)
    
    # 6. Output Generation
    PROJECT_DEPTHS = [0, 5, 10, 20, 30, 50, 75, 100, 125, 150, 200, 300, 500, 700, 1000]
    print("\n--- ZERO-SHOT NIO TEMPERATURE PROFILE ---")
    for d, temp in zip(PROJECT_DEPTHS, final_15_depths[0]):
        print(f"  {d:>4d}m : {temp:>6.2f} °C")
        
    print("\nNext step: Compare this output against ARGO float telemetry (Phase 3).")

if __name__ == "__main__":
    run_zeroshot_experiment()
